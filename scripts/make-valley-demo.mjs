// Generates src/data/valley-demo.json: synthetic boreholes sampled from analytic surfaces.
// The dataset exercises pinch-outs, locally absent units and boreholes that stop above bedrock.
import {writeFileSync} from "node:fs";

const ILLUSTRATIVE="Illustrative typical value for a synthetic dataset; not measured";
const units=[
  {id:"Made Ground",name:"Made Ground",color:"#7d6f86",gamma:19,t:(x,y)=>3.2*(1-((y-70)/45)**2)},
  {id:"Alluvium",name:"Alluvium",color:"#c2ab7c",gamma:18,gammaSat:19.5,t:(x,y)=>11*(1-((x-215)/125)**2)*(0.85+0.15*Math.sin(y/70))},
  {id:"Terrace Gravel",name:"Terrace Gravel",color:"#d08a4c",gamma:20,gammaSat:21,t:(x,y)=>6.5*(1-((x-135)**2+(y-215)**2)/105**2)},
  {id:"Mudstone",name:"Mudstone",color:"#6f7686",gamma:23,t:(x,y)=>9+0.025*y+2*Math.sin(x/80)},
  {id:"Sandstone",name:"Sandstone",color:"#b9925c",gamma:24,t:(x,y)=>16-0.012*x+1.5*Math.cos(y/60)},
  {id:"Granite",name:"Granite",color:"#a3999c",gamma:26,t:()=>Infinity}
];
const ground=(x,y)=>38+14*((x-210)/210)**2+3*Math.sin(y/55)+0.01*y;
// The terrain grid adds what the boreholes cannot resolve: gentle micro-relief and a stream incised along the
// valley floor. Collars were surveyed on the smooth surface, so they differ from the grid by a few decimetres.
const stream=(x,y)=>3.5*Math.exp(-(((x-(205+25*Math.sin(y/60)))/9)**2));
const dem=(x,y)=>ground(x,y)+0.4*Math.sin(x/23)*Math.cos(y/31)-stream(x,y);
// [id, x, y, final depth or null = drilled 8 m into granite]
const sites=[
  ["BH-01",20,30,null],["BH-02",130,25,9],["BH-03",240,40,null],["BH-04",390,30,null],
  ["BH-05",70,120,null],["BH-06",180,110,12],["BH-07",300,125,null],["BH-08",405,150,8],
  ["BH-09",25,220,null],["BH-10",120,200,null],["BH-11",215,230,null],["BH-12",330,215,14],
  ["BH-13",90,300,10],["BH-14",200,310,null],["BH-15",310,300,null],["BH-16",415,290,null]
];
const r1=(v)=>Math.round(v*10)/10;

const boreholes=sites.map(([id,x,y,final])=>{
  const stack=[];let top=0;
  for(const u of units){
    const t=Math.max(0,u.t(x,y));
    if(t>=0.05||t===Infinity)stack.push({unit:u.id,from:top,to:top+t});
    top+=t===Infinity?0:t;
  }
  const depth=final??r1(stack.at(-1).from+8);
  const intervals=[];
  for(const s of stack){
    const from=r1(s.from),to=r1(Math.min(s.to,depth));
    if(from>=depth)break;
    if(to>from)intervals.push({from,to,unit:s.unit});
  }
  return {id,x,y,z:Math.round(ground(x,y)*100)/100,intervals};
});

const cell=5,x0=-100,y0=-80,ncols=125,nrows=97,z=[];
for(let r=0;r<nrows;r++)for(let c=0;c<ncols;c++)z.push(Math.round(dem(x0+c*cell,y0+r*cell)*100)/100);
const project={
  name:"Synthetic valley",
  description:"Sixteen synthetic boreholes across a valley under a 5 m terrain grid: made ground near a road, alluvium thinning to zero on the flanks, a terrace-gravel lens that pinches out, a stream cut into the valley floor, and five holes that stop above bedrock. Generated by scripts/make-valley-demo.mjs; not a real site.",
  crs:"Local grid (m)",
  units:units.map(({id,name,color,gamma,gammaSat})=>({id,name,color,gamma,...(gammaSat?{gammaSat}:{}),source:ILLUSTRATIVE})),
  boreholes,
  terrain:{x0,y0,dx:cell,dy:cell,ncols,nrows,z,source:"Synthetic 5 m grid (scripts/make-valley-demo.mjs)"}
};
// Pretty-print the project but keep the long terrain array on one line.
writeFileSync(new URL("../src/data/valley-demo.json",import.meta.url),JSON.stringify(project,null,1).replace(/"z": \[[^\]]*\]/,m=>m.replace(/\s+/g,""))+"\n");
