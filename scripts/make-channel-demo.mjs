// Generates src/data/channel-demo.json and tests/fixtures/channel-truth.json: synthetic boreholes over a buried
// channel that was cut into dipping bedrock (an erosional unconformity), then filled with gravel and buried by
// alluvium. The fixture holds the true horizon elevations on a 10 m grid, to test how the model reproduces them.
import {writeFileSync} from "node:fs";

const ILLUSTRATIVE="Illustrative typical value for a synthetic dataset; not measured";
const units=[
  {id:"Alluvium",name:"Alluvium",color:"#c2ab7c",gamma:18,gammaSat:19.5},
  {id:"Channel Gravel",name:"Channel Gravel",color:"#d08a4c",erosive:true,gamma:20.5,gammaSat:21.5},
  {id:"Mudstone",name:"Mudstone",color:"#6f7686",gamma:22.5},
  {id:"Sandstone",name:"Sandstone",color:"#b9925c",gamma:24},
  {id:"Siltstone",name:"Siltstone",color:"#8a8170",gamma:23.5},
  {id:"Limestone",name:"Limestone",color:"#9fb4c0",gamma:26}
];
// Bedrock before erosion, dipping gently to the east-south-east.
const rockTop=(x,y)=>34-0.035*x-0.012*y;
const tMud=(x,y)=>9+0.01*y+0.8*Math.sin(x/70);
const tSand=x=>6+0.008*x;
const tSilt=(x,y)=>8+0.5*Math.cos(y/60);
// The channel: an erosion surface below the original rock top, deepest along a meandering axis.
const axis=y=>180+35*Math.sin(y/70);
const incision=(x,y)=>{const d=17*Math.exp(-(((x-axis(y))/38)**2))*(0.85+0.15*Math.cos(y/50));return d>0.3?d:0};
const alluvium=(x,y)=>2.2+1.2*Math.sin(x/55)*Math.cos(y/40);
const ground=(x,y)=>rockTop(x,y)+alluvium(x,y);

// True horizons after erosion: ground, then the base of each unit.
function horizons(x,y){
  const top=rockTop(x,y),cut=top-incision(x,y);
  const mud=Math.min(top-tMud(x,y),cut),sand=Math.min(top-tMud(x,y)-tSand(x),mud),silt=Math.min(top-tMud(x,y)-tSand(x)-tSilt(x,y),sand);
  return [ground(x,y),top,cut,mud,sand,silt];
}
const r2=v=>Math.round(v*100)/100,r1=v=>Math.round(v*10)/10;

// [id, x, y, final depth or null = drilled 6 m into limestone]; C-03/06/09/12 on the channel axis, C-02/05/08/11 on its flanks.
const sites=[
  ["C-01",30,25,null],["C-02",150,30,null],["C-03",191,22,null],["C-04",330,40,null],["C-05",255,95,null],
  ["C-06",212,88,null],["C-07",40,120,8],["C-08",160,150,null],["C-09",205,165,null],["C-10",320,140,null],
  ["C-11",230,215,null],["C-12",175,238,null],["C-13",60,230,null],["C-14",300,240,12],["C-15",110,80,null]
];
const boreholes=sites.map(([id,x,y,final])=>{
  const h=horizons(x,y),depths=h.map(z=>h[0]-z);
  const depth=final??r1(depths[5]+6);
  const intervals=[];
  for(let u=0;u<units.length;u++){
    const from=r1(depths[u]),to=r1(Math.min(u<5?depths[u+1]:Infinity,depth));
    if(from>=depth)break;
    if(to-from>=0.1)intervals.push({from,to,unit:units[u].id});
  }
  return {id,x,y,z:r2(h[0]),intervals};
});

const cell=5,x0=-40,y0=-40,ncols=89,nrows=69,z=[];
for(let r=0;r<nrows;r++)for(let c=0;c<ncols;c++){const x=x0+c*cell,y=y0+r*cell;z.push(r2(ground(x,y)+0.3*Math.sin(x/19)*Math.cos(y/27)))}

const project={
  name:"Synthetic buried channel",
  description:"Fifteen synthetic boreholes over a gravel-filled channel cut into dipping mudstone and sandstone, buried by alluvium, under a 5 m terrain grid. Channel Gravel is marked erosive: where it removed older units, their surfaces are cut at its base instead of thinning towards it. Generated by scripts/make-channel-demo.mjs; not a real site.",
  crs:"Local grid (m)",
  units:units.map(u=>({...u,source:ILLUSTRATIVE})),
  boreholes,
  terrain:{x0,y0,dx:cell,dy:cell,ncols,nrows,z,source:"Synthetic 5 m grid (scripts/make-channel-demo.mjs)"}
};
const compact=s=>s.replace(/"z": \[[^\]]*\]/,m=>m.replace(/\s+/g,""));
writeFileSync(new URL("../src/data/channel-demo.json",import.meta.url),compact(JSON.stringify(project,null,1))+"\n");

const names=["ground",...units.slice(0,5).map(u=>"base:"+u.id)],truth={x0:0,y0:0,d:10,ncols:37,nrows:27,horizons:{}};
for(const n of names)truth.horizons[n]=[];
for(let r=0;r<truth.nrows;r++)for(let c=0;c<truth.ncols;c++)horizons(c*10,r*10).forEach((v,k)=>truth.horizons[names[k]].push(r2(v)));
writeFileSync(new URL("../tests/fixtures/channel-truth.json",import.meta.url),JSON.stringify(truth)+"\n");
console.log(boreholes.map(b=>`${b.id} z=${b.z} ${b.intervals.map(i=>`${i.unit}:${i.from}-${i.to}`).join(" | ")}`).join("\n"));
